/** Core domain types shared by mock data, lib/api and UI components. */

export type Category =
  | "Fashion"
  | "Food"
  | "Fitness"
  | "Education"
  | "Technology"
  | "Beauty"
  | "Travel"
  | "Lifestyle"
  | "Gaming"
  | "Finance"
  | "Real Estate";

export type City =
  | "Hyderabad"
  | "Kakinada"
  | "Rajahmundry"
  | "Vijayawada"
  | "Visakhapatnam"
  | "Bengaluru"
  | "Chennai"
  | "Mumbai";

export type Platform = "Instagram" | "YouTube" | "X" | "LinkedIn";

export type TrustState =
  | "registered-creator"
  | "verified-creator"
  | "verified-brand"
  | "verified-campaign"
  | "verification-pending"
  | "action-required";

export interface PlatformStat {
  platform: Platform;
  handle: string;
  followers: number;
  /** Percent, e.g. 4.2 for 4.2%. */
  engagementRate: number;
}

export interface PortfolioItem {
  id: string;
  title: string;
  brand?: string;
  category: Category;
}

export interface CollaborationSummary {
  id: string;
  brandName: string;
  campaignTitle: string;
  completedOn: string;
}

export interface Creator {
  id: string;
  userId: string;
  slug: string;
  name: string;
  username: string;
  category: Category;
  city: City;
  bio: string;
  trust: TrustState;
  platforms: PlatformStat[];
  portfolio: PortfolioItem[];
  collaborations: CollaborationSummary[];
  /** Indicative starting rate in INR for a single deliverable. Not a quote. */
  startingRateInr: number;
  joinedOn: string;
}

export interface Brand {
  id: string;
  slug: string;
  name: string;
  industry: Category;
  city: City;
  description: string;
  website?: string;
  trust: TrustState;
  activeCampaigns: number;
  completedCampaigns: number;
}

export type CampaignStatus = "open" | "closing-soon" | "closed";

export interface Campaign {
  id: string;
  slug: string;
  title: string;
  brandName: string;
  brandSlug: string;
  category: Category;
  city: City | "Remote";
  /** Total campaign budget in INR. */
  budgetInr: number;
  deliverables: string[];
  platforms: Platform[];
  deadline: string;
  applicants: number;
  status: CampaignStatus;
  trust: TrustState;
  summary: string;
}

export type ApplicationStatus =
  | "submitted"
  | "shortlisted"
  | "accepted"
  | "rejected"
  | "withdrawn";

export interface Application {
  id: string;
  campaignId: string;
  creatorId: string;
  status: ApplicationStatus;
  submittedOn: string;
  /** Recommended-match score out of 100. Not a guarantee. */
  matchScore: number;
  creatorName?: string;
  proposal?: string;
  expectedPriceInr?: number;
}

export type CollaborationStatus =
  | "pending"
  | "accepted"
  | "active"
  | "content-submitted"
  | "under-review"
  | "revision-requested"
  | "approved"
  | "published"
  | "completed";

export interface CollaborationEvent {
  status: CollaborationStatus;
  timestamp: string;
  note?: string;
}

export interface Collaboration {
  id: string;
  campaignId: string;
  creatorId: string;
  status: CollaborationStatus;
  timeline: CollaborationEvent[];
}

export type NotificationKind =
  | "new-campaign"
  | "campaign-match"
  | "application-submitted"
  | "application-accepted"
  | "application-rejected"
  | "application-withdrawn"
  | "new-message"
  | "content-review"
  | "revision-requested"
  | "content-approved"
  | "payment"
  | "subscription";

export interface AppNotification {
  id: string;
  kind: NotificationKind;
  title: string;
  body: string;
  timestamp: string;
  read: boolean;
}

export interface Message {
  id: string;
  conversationId: string;
  senderId: string;
  senderName: string;
  body: string;
  timestamp: string;
  /** Set when the message is generated by HRIX rather than a person. */
  system?: boolean;
}

export interface Conversation {
  id: string;
  campaignTitle?: string;
  participantName: string;
  participantRole: "creator" | "brand";
  lastMessage: string;
  lastMessageAt: string;
  unreadCount: number;
}

export type SubscriptionStatus = "active" | "past-due" | "canceled" | "none";

export interface Subscription {
  status: SubscriptionStatus;
  planId?: string;
  planName: "HRIX Entry" | "Profile Audit" | "Creator Growth" | "Brand Directory Access" | string;
  priceInr: number;
  renewsOn?: string;
  isExpired?: boolean;
  durationDays?: number;
  billingPeriod?: string;
}

export interface Invoice {
  id: string;
  description: string;
  amountInr: number;
  issuedOn: string;
  status: "paid" | "due" | "failed";
}
